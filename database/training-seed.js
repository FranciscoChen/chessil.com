#!/usr/bin/env node
'use strict';

// Regenerate seed SQL from the canonical curriculum; this never connects to DB.
// node database/training-seed.js          writes the two migration files
// node database/training-seed.js --check  checks parity without writing files
const fs = require('node:fs');
const path = require('node:path');
const START = '-- BEGIN CURATED TRAINING PUZZLES';
const MIGRATION_START = '-- BEGIN TRAINING MIGRATION';
const MIGRATION_END = '-- END TRAINING MIGRATION';

function puzzlesFrom(curriculum) {
  if (!Array.isArray(curriculum.tactics) || curriculum.tactics.length === 0) {
    throw new Error('Refusing to seed an empty tactics curriculum');
  }
  const seen = new Set();
  return curriculum.tactics.map(lesson => {
    if (typeof lesson.id !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9_-]{0,95}$/.test(lesson.id) || seen.has(lesson.id) ||
        typeof lesson.fen !== 'string' || lesson.fen.length > 128 ||
        typeof lesson.title !== 'string' || !lesson.title ||
        !Array.isArray(lesson.moves) || !lesson.moves.length || lesson.moves.length > 64 ||
        !lesson.moves.every(move => /^[a-h][1-8][a-h][1-8][qrbn]?$/.test(move))) {
      throw new Error('Invalid curated tactic: ' + lesson.id);
    }
    seen.add(lesson.id);
    const theme = lesson.theme || lesson.pattern || lesson.title;
    if (typeof theme !== 'string') throw new Error('Expected a text theme for ' + lesson.id);
    return { id: lesson.id, fen: lesson.fen, solution: lesson.moves, theme, title: lesson.title };
  });
}

function migrationFor(curriculum, prior) {
  const schema = prior.split(START)[0].trimEnd();
  const json = JSON.stringify(puzzlesFrom(curriculum), null, 2);
  if (json.includes('$training_puzzles$')) throw new Error('Unexpected SQL delimiter in curriculum');
  return schema + '\n\n' + START + '\n' +
    '-- Generated by node database/training-seed.js from web/training/curriculum.js.\n' +
    `INSERT INTO training_puzzles (id, fen, solution, theme, title)
SELECT id, fen, solution, theme, title
FROM jsonb_to_recordset($training_puzzles$
${json}
$training_puzzles$::jsonb)
AS puzzle(id text, fen text, solution jsonb, theme text, title text)
ON CONFLICT (id) DO UPDATE SET
    fen = EXCLUDED.fen,
    solution = EXCLUDED.solution,
    theme = EXCLUDED.theme,
    title = EXCLUDED.title,
    updated_at = NOW()
WHERE (training_puzzles.fen, training_puzzles.solution, training_puzzles.theme, training_puzzles.title)
    IS DISTINCT FROM (EXCLUDED.fen, EXCLUDED.solution, EXCLUDED.theme, EXCLUDED.title);
`;
}

function updatesFor(prior, migration) {
  const block = MIGRATION_START + '\n' + migration + MIGRATION_END + '\n';
  if (!prior.includes(MIGRATION_START)) return prior.trimEnd() + '\n\n' + block;
  const start = prior.indexOf(MIGRATION_START), end = prior.indexOf(MIGRATION_END, start);
  if (end === -1) throw new Error('Incomplete training migration marker');
  return prior.slice(0, start) + block + prior.slice(end + MIGRATION_END.length).replace(/^\r?\n/, '');
}

function main(check) {
  const curriculum = require('../web/training/curriculum');
  const migrationPath = path.join(__dirname, 'training.sql');
  const updatesPath = path.join(__dirname, 'updates.sql');
  const priorMigration = fs.readFileSync(migrationPath, 'utf8');
  const priorUpdates = fs.readFileSync(updatesPath, 'utf8');
  const migration = migrationFor(curriculum, priorMigration);
  const updates = updatesFor(priorUpdates, migration);
  if (check) {
    if (migration !== priorMigration || updates !== priorUpdates) throw new Error('Training SQL is stale; run node database/training-seed.js');
    console.log('Training SQL matches all ' + curriculum.tactics.length + ' curriculum puzzles.');
  } else {
    fs.writeFileSync(migrationPath, migration);
    fs.writeFileSync(updatesPath, updates);
    console.log('Generated training.sql and updates.sql for ' + curriculum.tactics.length + ' curriculum puzzles.');
  }
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node database/training-seed.js [--check]');
    main(process.argv.includes('--check'));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { puzzlesFrom, migrationFor, updatesFor };
