-- Account progress is per lesson. Guests keep the same shape in local storage.
CREATE TABLE IF NOT EXISTS training_progress (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_id text NOT NULL CHECK (lesson_id ~ '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,95}$'),
    stage smallint NOT NULL DEFAULT 0 CHECK (stage BETWEEN 0 AND 3),
    completed boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT NOW(),
    PRIMARY KEY (user_id, lesson_id)
);

-- Small, curated tactics dataset. IDs match the curriculum; solutions are UCI.
CREATE TABLE IF NOT EXISTS training_puzzles (
    id text PRIMARY KEY CHECK (id ~ '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,95}$'),
    fen text NOT NULL CHECK (length(fen) BETWEEN 20 AND 128),
    solution jsonb NOT NULL CHECK (jsonb_typeof(solution) = 'array' AND jsonb_array_length(solution) BETWEEN 1 AND 64),
    theme text NOT NULL,
    title text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT NOW()
);

