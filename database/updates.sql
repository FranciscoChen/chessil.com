-- Account progress is per lesson. Guests keep the same shape in local storage.
CREATE TABLE IF NOT EXISTS training_progress (
    user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lesson_id text NOT NULL CHECK (lesson_id ~ '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,95}$'),
