/* Build both Sculpted colors from one silhouette per piece. SVG-only gradients,
 * clipped reflections and restrained opposite-color inlays; no raster filters.
 * Edit web/assets/sculpted-pieces.json, regenerate, then inspect actual renders. */
const fs=require('fs'),path=require('path');
const {createHash}=require('crypto');
const versions={},selectors=[];
const root=path.resolve(__dirname,'..'),pieces=require('../assets/sculpted-pieces.json');
const palettes={
 w:{label:'Ivory',stops:['#fffef5','#f9f2dc','#e5d7b8','#c7b593'],rim:'#fffdf4',ink:'#34434a',shine:'#fffef8'},
 b:{label:'Obsidian',stops:['#61747c','#334650','#182830','#0e1720'],rim:'#aebebf',ink:'#e4dfcb',shine:'#c3d9d9'}
};
for(const [name,piece] of Object.entries(pieces))for(const [color,palette] of Object.entries(palettes)) {
 const id='sculpted-'+color+piece.code;
 const stroke=path=>`<path d="${path}"/>`;
 const content=`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000" role="img" aria-labelledby="${id}-title ${id}-desc">
  <title id="${id}-title">${palette.label} ${name}</title>
  <desc id="${id}-desc">Sculpted chess piece with polished surfaces and ${color==='w'?'dark':'ivory'} carved inlays.</desc>
  <defs>
    <linearGradient id="${id}-body" x1="0" y1="0" x2="1" y2="0.65">
      <stop offset="0" stop-color="${palette.stops[0]}"/><stop offset=".3" stop-color="${palette.stops[1]}"/>
      <stop offset=".68" stop-color="${palette.stops[2]}"/><stop offset="1" stop-color="${palette.stops[3]}"/>
    </linearGradient>
    <radialGradient id="${id}-light" cx=".28" cy=".18" r=".8">
      <stop stop-color="${palette.shine}" stop-opacity="${color==='w'?'.5':'.25'}"/><stop offset="1" stop-color="${palette.shine}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="${id}-groove" x1="0" y1="0" x2="0" y2="1">
      <stop stop-color="${palette.ink}" stop-opacity=".95"/><stop offset="1" stop-color="${palette.ink}" stop-opacity=".7"/>
    </linearGradient>
    <clipPath id="${id}-clip"><path d="${piece.shape}"/></clipPath>
  </defs>
  <path d="${piece.shape}" fill="url(#${id}-body)" stroke="#15232b" stroke-width="18" stroke-linejoin="round"/>
  <g clip-path="url(#${id}-clip)">
    <path d="${piece.shape}" fill="url(#${id}-light)"/>
    <path d="${piece.shape}" fill="none" stroke="${palette.rim}" stroke-width="7" stroke-linejoin="round" opacity=".58"/>
    <path d="M248 832Q500 846 752 832V882H248Z" fill="${color==='w'?'#8b7755':'#050b11'}" opacity=".17"/>
    <g fill="none" stroke="${palette.rim}" stroke-width="17" stroke-linecap="round" stroke-linejoin="round" opacity=".32" transform="translate(0 4)">
      ${piece.inlay.map(stroke).join('')}${stroke('M255 813Q500 826 745 813')}
    </g>
    <g fill="none" stroke="url(#${id}-groove)" stroke-width="11" stroke-linecap="round" stroke-linejoin="round">
      ${piece.inlay.map(stroke).join('')}${stroke('M255 813Q500 826 745 813')}
    </g>
    <path d="${piece.glint}" fill="none" stroke="${palette.shine}" stroke-width="13" stroke-linecap="round" opacity="${color==='w'?'.8':'.45'}"/>
    ${piece.eye?`<path d="${piece.eye}" fill="${palette.ink}"/><circle cx="325" cy="326" r="4" fill="${palette.stops[0]}"/>`:''}
    ${piece.nostril?`<circle cx="${piece.nostril[0]}" cy="${piece.nostril[1]}" r="${piece.nostril[2]}" fill="${palette.ink}" opacity=".9"/>`:''}
  </g>
</svg>
<!-- Adapted from ${name} by Benjamin Kinard, The Noun Project. CC BY 3.0: https://creativecommons.org/licenses/by/3.0/
     ${piece.source}
     Sculpted edition: matched silhouettes, smoothed incisions, shading and inlays. -->
`.split('\n').map(line=>line.trimEnd()).join('\n');
 const file=color+piece.code;
 fs.writeFileSync(path.join(root,'web/img/pieces',file+'.svg'),content);
 versions[file]=createHash('sha256').update(content).digest('hex').slice(0,12);
 selectors.push(`html[data-pieces="sculpted"] cg-board piece.${color==='w'?'white':'black'}.${name}{background-image:url("/img/pieces/${file}.svg?v=${versions[file]}");}`);
}

fs.writeFileSync(path.join(root,'assets/sculpted-versions.json'),JSON.stringify(versions,null,2)+'\n');
fs.writeFileSync(path.join(root,'src/sculpted-pieces.css'),'/* Generated by build-pieces.js. Sculpted set shared with the landing page. */\n'+selectors.join('\n')+'\n');
